export function Icon({ name, size = 16, className }: { name: string; size?: number; className?: string }) {
  const C = UI[name];
  if (!C) return null;
  return <C size={size} className={className} style={name === 'star-filled' ? { fill: 'currentColor' } : undefined} />;
}

