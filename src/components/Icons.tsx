export const ICON_CHOICES = Object.keys(TYPE_ICONS);

export function TypeIcon({ icon, color, size = 16 }: { icon?: string; color?: string; size?: number }) {
  const C = icon ? TYPE_ICONS[icon] : undefined;
  if (C) return <C size={size} style={color ? { color } : undefined} />;
  // Legacy fallback: user-created types from the emoji era render their emoji as-is.
  if (icon) return <span style={{ fontSize: size - 1, lineHeight: 1 }}>{icon}</span>;
  return <LuBox size={size} style={color ? { color } : undefined} />;
}
